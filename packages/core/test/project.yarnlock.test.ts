// M7c — berry yarn.lock parser + lockfile tie graph (project/yarnlock.ts,
// lockfile.ts): GWT over the strict subset (descriptors, peer suffixes,
// workspace refs), the non-berry refusal (yarn 1.x), and the graph shape
// (canonical nodes, locate() paths, semver fallback edges).

import { describe, expect, test } from "bun:test";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { yarnLockfileGraph } from "../src/project/lockfile.js";
import { parseDescriptor, parseYarnLock, parseYarnLockFile, toDescriptor } from "../src/project/yarnlock.js";
import { UsageError } from "../src/util/errors.js";

const BERRY = `# This file is generated by Yarn.
__metadata:
  version: 6
  cacheKey: 6

"lodash@^4.17.21, lodash@npm:4.17.21, lodash@~4.17.21":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"
  dependencies:
    ms: 2.1.3
  checksum: "abc123"

"ms@npm:2.1.3":
  version: 2.1.3
  resolution: "ms@npm:2.1.3"
  checksum: "def456"
`;

const CLASSIC_V1 = `# yarn lockfile v1

lodash@^4.17.21:
  version "4.17.21"
  resolved "https://registry.npmjs.org/lodash/-/lodash-4.17.21.tgz"
`;

describe("parseDescriptor", () => {
  test("given a bare name, when parsed, then no protocol or range", () => {
    expect(parseDescriptor("myapp")).toEqual({ name: "myapp", protocol: "", range: "", peers: "" });
  });

  test("given a default-protocol range, when parsed, then protocol is npm and the range kept", () => {
    expect(parseDescriptor("lodash@^4.17.21")).toEqual({
      name: "lodash",
      protocol: "npm",
      range: "^4.17.21",
      peers: "",
    });
  });

  test("given a scoped name with an explicit protocol, when parsed, then the scope stays in the name", () => {
    expect(parseDescriptor("@scope/pkg@npm:1.0.0")).toEqual({
      name: "@scope/pkg",
      protocol: "npm",
      range: "1.0.0",
      peers: "",
    });
  });

  test("given a workspace protocol, when parsed, then protocol is workspace", () => {
    expect(parseDescriptor("myapp@workspace:^")).toEqual({
      name: "myapp",
      protocol: "workspace",
      range: "^",
      peers: "",
    });
  });

  test("given a peer-suffixed descriptor, when parsed, then the range and the peer suffix split", () => {
    expect(parseDescriptor("pkg@npm:1.0.0(dep@^2.0.0)")).toEqual({
      name: "pkg",
      protocol: "npm",
      range: "1.0.0",
      peers: "(dep@^2.0.0)",
    });
  });
});

describe("toDescriptor (dependency-map values)", () => {
  test("given a bare range value, when converted, then name@range results", () => {
    expect(toDescriptor("ms", "2.1.3")).toBe("ms@2.1.3");
  });

  test("given a protocol-prefixed range (workspace:^), when converted, then the dep name is prefixed", () => {
    expect(toDescriptor("myapp", "workspace:^")).toBe("myapp@workspace:^");
  });

  test("given an alias descriptor value, when converted, then it is kept as-is", () => {
    expect(toDescriptor("my-alias", "realpkg@^1.0.0")).toBe("realpkg@^1.0.0");
  });

  test("given a scoped alias descriptor, when converted, then it is kept as-is", () => {
    expect(toDescriptor("@scope/alias", "@scope/real@^1.0.0")).toBe("@scope/real@^1.0.0");
  });

  test("given a scoped dep name with a bare range, when converted, then name@range results", () => {
    expect(toDescriptor("@scope/alias", "^1.0.0")).toBe("@scope/alias@^1.0.0");
  });
});

describe("parseYarnLock (berry strict subset)", () => {
  test("given a berry v6 lockfile, when parsed, then entries carry version, descriptors, deps and checksum", () => {
    const entries = parseYarnLock(BERRY);
    expect(entries.length).toBe(2);
    const lodash = entries[0];
    const ms = entries[1];
    expect(lodash?.name).toBe("lodash");
    expect(lodash?.version).toBe("4.17.21");
    expect(lodash?.protocol).toBe("npm");
    expect(lodash?.descriptors).toEqual(["lodash@^4.17.21", "lodash@npm:4.17.21", "lodash@~4.17.21"]);
    expect([...(lodash?.dependencies ?? [])]).toEqual([["ms", "ms@2.1.3"]]);
    expect(lodash?.checksum).toBe("abc123");
    expect(ms?.name).toBe("ms");
    expect(ms?.version).toBe("2.1.3");
    expect(ms?.checksum).toBe("def456");
  });

  test("given a peer-suffixed key and a peerDependencies map, when parsed, then the peers stay separate from the dependencies", () => {
    const text = `__metadata:
  version: 8
  cacheKey: 8

"pkg@npm:1.0.0(other@^2.0.0), pkg@npm:1.0.0":
  version: 1.0.0
  resolution: "pkg@npm:1.0.0"
  dependencies:
    ms: 2.1.3
  peerDependencies:
    other: ^2.0.0
  languageName: node
  engines:
    node: ">=18"
`;
    const [entry] = parseYarnLock(text);
    expect(entry?.name).toBe("pkg");
    expect(entry?.descriptors).toEqual(["pkg@npm:1.0.0(other@^2.0.0)", "pkg@npm:1.0.0"]);
    expect([...(entry?.dependencies ?? [])]).toEqual([["ms", "ms@2.1.3"]]);
    expect([...(entry?.peerDependencies ?? [])]).toEqual([["other", "other@^2.0.0"]]);
  });

  test("given a workspace entry, when parsed, then its protocol is workspace (no version)", () => {
    const text = `__metadata:
  version: 6

"myapp@workspace:.", myapp@workspace:^":
  version: 0.0.0-use-local
  resolution: "myapp@workspace:."
  dependencies:
    lodash: ^4.17.21
`;
    const [entry] = parseYarnLock(text);
    expect(entry?.name).toBe("myapp");
    expect(entry?.protocol).toBe("workspace");
    expect([...(entry?.dependencies ?? [])]).toEqual([["lodash", "lodash@^4.17.21"]]);
  });

  test("given a yarn 1.x classic lockfile, when parsed, then a UsageError names the unsupported format", () => {
    expect(() => parseYarnLock(CLASSIC_V1)).toThrow(UsageError);
    expect(() => parseYarnLock(CLASSIC_V1)).toThrow(/not a berry/);
  });

  test("given a lockfile whose __metadata version is below 2, when parsed, then the version is refused", () => {
    expect(() => parseYarnLock("__metadata:\n  version: 1\n")).toThrow(/need >= 2/);
  });

  test("given a line outside the strict subset, when parsed, then a UsageError names the line", () => {
    const text = `__metadata:
  version: 6

"lodash@npm:4.17.21":
  version: 4.17.21
   broken-indent: no
`;
    expect(() => parseYarnLock(text)).toThrow(UsageError);
    expect(() => parseYarnLock(text)).toThrow(/line 6/);
  });

  test("given empty text, when parsed, then the missing __metadata is refused", () => {
    expect(() => parseYarnLock("")).toThrow(/not a berry/);
  });
});

describe("parseYarnLockFile", () => {
  test("given a root without yarn.lock, when read, then null", () => {
    const root = mkdtempSync(join(tmpdir(), "callis-yarn-"));
    try {
      expect(parseYarnLockFile(root)).toBeNull();
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  test("given a root with a berry yarn.lock, when read, then the entries parse", () => {
    const root = mkdtempSync(join(tmpdir(), "callis-yarn-"));
    try {
      writeFileSync(join(root, "yarn.lock"), BERRY);
      expect(parseYarnLockFile(root)?.length).toBe(2);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});

describe("yarnLockfileGraph", () => {
  function fixture(): { root: string } {
    const root = mkdtempSync(join(tmpdir(), "callis-yarngraph-"));
    writeFileSync(join(root, "yarn.lock"), BERRY);
    writeFileSync(join(root, "package.json"), JSON.stringify({ name: "app", dependencies: { lodash: "^4.17.21" } }));
    return { root };
  }

  test("given a lockfile + workspace manifest + locate(), when built, then nodes carry name/version/path and the edges span root and entry deps", () => {
    const { root } = fixture();
    try {
      const g = yarnLockfileGraph(root, {
        workspaceDirs: [root],
        locate: (name, version) => (name === "lodash" ? `/extracted/${name}@${version}` : undefined),
      });
      expect(g).not.toBe(null);
      const lodash = g?.nodes.get("lodash@4.17.21");
      expect(lodash).toEqual({
        key: "lodash@4.17.21",
        name: "lodash",
        version: "4.17.21",
        path: "/extracted/lodash@4.17.21",
      });
      expect(g?.nodes.get("ms@2.1.3")).toEqual({ key: "ms@2.1.3", name: "ms", version: "2.1.3" });
      expect(g?.nodes.get(`ws:${root}`)).toEqual({ key: `ws:${root}`, name: "app", path: root });
      expect(g?.edges).toContainEqual([`ws:${root}`, "lodash@4.17.21"]);
      expect(g?.edges).toContainEqual(["lodash@4.17.21", "ms@2.1.3"]);
      expect(g?.source).toBe("lockfile");
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  test("given multiple range aliases for one version, when built, then a SINGLE canonical node results", () => {
    const { root } = fixture();
    try {
      const g = yarnLockfileGraph(root, { workspaceDirs: [root] });
      expect([...(g?.nodes.keys() ?? [])].filter((k) => k.startsWith("lodash@"))).toEqual(["lodash@4.17.21"]);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  test("given a dep range that only matches by semver, when built, then the edge still resolves to the entry", () => {
    const root = mkdtempSync(join(tmpdir(), "callis-yarngraph-"));
    writeFileSync(
      join(root, "yarn.lock"),
      `__metadata:
  version: 6

"ms@^2.1.0, ms@npm:2.1.3":
  version: 2.1.3
  resolution: "ms@npm:2.1.3"
`,
    );
    writeFileSync(join(root, "package.json"), JSON.stringify({ name: "app", dependencies: { ms: "^2.1.0" } }));
    try {
      const g = yarnLockfileGraph(root, { workspaceDirs: [root] });
      expect(g?.edges).toContainEqual([`ws:${root}`, "ms@2.1.3"]);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  test("given a workspace-protocol dep, when built, then no package node is invented for it (and no edge)", () => {
    const root = mkdtempSync(join(tmpdir(), "callis-yarngraph-"));
    writeFileSync(
      join(root, "yarn.lock"),
      `__metadata:
  version: 6

"lodash@^4.17.21, lodash@npm:4.17.21":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"
  dependencies:
    myapp: myapp@workspace:^
`,
    );
    writeFileSync(join(root, "package.json"), JSON.stringify({ name: "app", dependencies: { myapp: "workspace:^" } }));
    try {
      const g = yarnLockfileGraph(root, { workspaceDirs: [root] });
      expect([...(g?.nodes.keys() ?? [])]).toContain(`ws:${root}`);
      expect([...(g?.nodes.keys() ?? [])]).not.toContain("myapp@workspace:^");
      expect(g?.edges.some(([from, to]) => from === `ws:${root}` && to.includes("myapp"))).toBe(false);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  test("given a metadata-only lockfile, when built, then null (no nodes)", () => {
    const root = mkdtempSync(join(tmpdir(), "callis-yarngraph-"));
    writeFileSync(join(root, "yarn.lock"), "__metadata:\n  version: 6\n  cacheKey: 6\n");
    try {
      expect(yarnLockfileGraph(root, { workspaceDirs: [root] })).toBeNull();
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  test("given a root without yarn.lock, when built, then null", () => {
    const root = mkdtempSync(join(tmpdir(), "callis-yarngraph-"));
    try {
      expect(yarnLockfileGraph(root, {})).toBeNull();
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});
