// CLI-level regression: the e2e gate runs EVERY demo with a relative
// --project and a relative --cache-dir INSIDE the demo tree
// (examples/... --cache-dir examples/.../out/cache). The PnP extraction dir
// becomes instance.realDir, so its path shape used to follow the cache dir
// (relative) while the resolved files were absolute — instance attribution
// of loaded files broke and a REACHABLE finding degraded to UNREACHABLE.
describe("CLI with e2e-shaped arguments (relative project + in-project cache-dir)", () => {
  const CLI = join(import.meta.dir, "..", "..", "cli", "src", "main.ts");

  /** A minimal PnP demo: the app calls the vulnerable package from a cache zip. */
  function pnpCliFixture(base: string): void {
    const root = join(base, "proj");
    const zipDir = join(root, ".yarn", "cache");
    mkdirSync(zipDir, { recursive: true });
    mkdirSync(join(root, "src"), { recursive: true });
    mkdirSync(join(root, "osv"), { recursive: true });
    writeFileSync(join(root, ".pnp.cjs"), "/* layout marker only — callis never executes this file */\n");
    writeFileSync(
      join(root, "package.json"),
      JSON.stringify({ name: "app", version: "1.0.0", main: "src/main.js", dependencies: { lodash: "4.17.20" } }),
    );
    // NOTE: the export call uses the assignment shape (as the golden demos
    // do) — a call nested inside another call's arguments at module top
    // level is not recorded as a distinct site yet (pre-existing M2 IR
    // limitation, all layouts).
    writeFileSync(
      join(root, "src", "main.js"),
      'const _ = require("lodash");\nconst greeting = _.template("x")({});\nconsole.log(greeting);\n',
    );
    writeFileSync(
      join(zipDir, "lodash-npm-4.17.20-abc.zip"),
      makeZip([
        { name: "package.json", data: JSON.stringify({ name: "lodash", version: "4.17.20", main: "index.js" }) },
        { name: "index.js", data: "function template(text) { return text; }\nmodule.exports = { template };\n" },
      ]),
    );
    writeFileSync(
      join(root, "sbom.json"),
      JSON.stringify({
        bomFormat: "CycloneDX",
        specVersion: "1.5",
        version: 1,
        components: [{ type: "library", name: "lodash", version: "4.17.20", purl: "pkg:npm/lodash@4.17.20" }],
        dependencies: [{ ref: "app" }, { ref: "pkg:npm/lodash@4.17.20", dependsOn: ["app"] }],
      }),
    );
    writeFileSync(
      join(root, "osv", "GHSA-424h-2jq2-7369.json"),
      JSON.stringify({
        id: "GHSA-424h-2jq2-7369",
        summary: "Prototype pollution in lodash",
        affected: [
          {
            package: { name: "lodash", ecosystem: "npm" },
            ranges: [{ type: "SEMVER", events: [{ introduced: "0" }, { fixed: "4.17.21" }] }],
          },
        ],
      }),
    );
  }

  test("given a PnP demo analyzed with RELATIVE --project and a RELATIVE --cache-dir inside the project, when the CLI runs, then the finding is REACHABLE and the exit code is 1", async () => {
    const base = mkdtempSync(join(tmpdir(), "callis-pnp-cli-"));
    const savedCwd = process.cwd();
    pnpCliFixture(base);
    try {
      process.chdir(base);
      const r = Bun.spawnSync(
        [
          "bun",
          CLI,
          "--project",
          "proj",
          "--sbom",
          "proj/sbom.json",
          "--osv-dir",
          "proj/osv",
          "--format",
          "json",
          "--output",
          join(base, "out", "report"),
          "--cache-dir",
          join("proj", "out", "cache"),
        ],
        {
          stdout: "pipe",
          stderr: "pipe",
        },
      );
      expect(r.exitCode).toBe(1);
      const report = JSON.parse(readFileSync(join(base, "out", "report.json"), "utf8")) as {
        findings: { id: string; verdict: string; evidence: { loaded: boolean } }[];
      };
      expect(report.findings.length).toBe(1);
      expect(report.findings[0]?.id).toBe("GHSA-424h-2jq2-7369");
      expect(report.findings[0]?.verdict).toBe("REACHABLE");
      expect(report.findings[0]?.evidence.loaded).toBe(true);
    } finally {
      process.chdir(savedCwd);
      await rm(base, { recursive: true, force: true });
    }
  });
});
