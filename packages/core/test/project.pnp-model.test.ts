interface FixtureOpts {
  /** install-state.gz content (a JSON array), or undefined for the degraded case. */
  installState?: unknown;
  /** cache zips: folderName -> zip bytes. */
  zips?: Record<string, Buffer>;
  /** yarn.lock content (undefined = absent). */
  lock?: string;
  /** app package.json. */
  appPkg?: Record<string, unknown>;
  /** extra files below the project root. */
  files?: Record<string, string>;
  /** write the .pnp.cjs marker (a nodeLinker: node-modules install has none). */
  marker?: boolean;
}

function mkPnpFixture(opts: FixtureOpts = {}): {
  root: string;
  cacheDir: string;
  globalCache: string;
  cleanup: () => Promise<void>;
} {
  const base = mkdtempSync(join(tmpdir(), "callis-pnp-model-"));
  const root = join(base, "proj");
  const cacheDir = join(base, "cache");
  const globalCache = join(base, "global-cache");
  mkdirSync(root, { recursive: true });
  mkdirSync(join(root, ".yarn", "cache"), { recursive: true });
  mkdirSync(globalCache, { recursive: true });
  if (opts.marker !== false)
    writeFileSync(join(root, ".pnp.cjs"), "/* layout marker only — callis never executes this file */\n");
  writeFileSync(
    join(root, "package.json"),
    JSON.stringify(
      opts.appPkg ?? { name: "app", version: "1.0.0", main: "src/main.js", dependencies: { lodash: "^4.17.21" } },
    ),
  );
  if (opts.lock !== undefined) writeFileSync(join(root, "yarn.lock"), opts.lock);
  if (opts.installState !== undefined) {
    writeFileSync(join(root, ".yarn", "install-state.gz"), gzipSync(JSON.stringify(opts.installState)));
  }
  for (const [folderName, zip] of Object.entries(opts.zips ?? {})) {
    writeFileSync(join(root, ".yarn", "cache", folderName), zip);
  }
  for (const [rel, content] of Object.entries(opts.files ?? {})) {
    mkdirSync(join(root, rel, ".."), { recursive: true });
    writeFileSync(join(root, rel), content);
  }
  return {
    root,
    cacheDir,
    globalCache,
    cleanup: async () => rm(base, { recursive: true, force: true }),
  };
}

const INSTALL_STATE = [
  {
    version: 5,
    folderName: "lodash-npm-4.17.21-abc.zip",
    packageManifest: { name: "lodash", version: "4.17.21", resolution: "lodash@npm:4.17.21" },
  },
  { version: 5, folderName: "ms-npm-2.1.3-def.zip", packageManifest: { name: "ms", version: "2.1.3" } },
];

function happyFixture(): {
  root: string;
  cacheDir: string;
  globalCache: string;
  cleanup: () => Promise<void>;
} {
  const f = mkPnpFixture({
    installState: INSTALL_STATE,
    zips: {
      "lodash-npm-4.17.21-abc.zip": LodashZip(),
      "ms-npm-2.1.3-def.zip": MsZip(),
    },
    lock: BERRY_LOCK,
  });
  mkdirSync(join(f.root, "src"), { recursive: true });
  return f;
}

